TASK_TYPES = {
    "analysis": {"icon": "🔍", "label": "Анализ", "description": "Исследование, аудит, разбор данных"},
    "prototype": {"icon": "🔨", "label": "Прототип", "description": "Создание MVP, черновик, быстрый билд"},
    "communication": {"icon": "💬", "label": "Коммуникация", "description": "Разговоры, посты, нетворкинг"},
    "research": {"icon": "📚", "label": "Исследование", "description": "Изучение конкурентов, трендов, инструментов"},
}


def format_starter_prompt(prompt_data: dict, goal: dict) -> str:
    """Форматирует стартовый промпт для показа пользователю."""
    task_type = TASK_TYPES.get(prompt_data["type"], {"icon": "📋", "label": "Задача"})
    return (
        f"{goal['icon']} {goal['title']}\n"
        f"{task_type['icon']} {task_type['label']}: **{prompt_data['title']}**\n"
        f"⏱ {prompt_data['duration']}  |  ✨ +{prompt_data['xp']} XP\n\n"
        f"{prompt_data['prompt']}"
    )


def get_random_narrative(key: str, **kwargs) -> str:
    """Возвращает случайный нарратив по ключу с подстановкой переменных."""
    import random
    options = LARP_NARRATIVES.get(key, [])
    if isinstance(options, list):
        text = random.choice(options)
    else:
        text = options
    return text.format(**kwargs) if kwargs else text
